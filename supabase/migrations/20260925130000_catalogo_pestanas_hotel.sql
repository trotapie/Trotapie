-- Vincular títulos ya guardados, incluidas las traducciones. No se altera su contenido.
insert into public.catalogo_pestanas_hotel (titulo_es, icono)
select distinct on (lower(regexp_replace(btrim(t.titulo), '[[:space:]]+', ' ', 'g')))
  btrim(t.titulo), s.icono
from public.hotel_detalle_secciones s
join public.hotel_detalle_secciones_traducciones t on t.seccion_id = s.id and t.idioma_id = 1
where not exists (
  select 1 from public.catalogo_pestanas_hotel c
  where lower(regexp_replace(btrim(c.titulo_es), '[[:space:]]+', ' ', 'g')) =
    lower(regexp_replace(btrim(t.titulo), '[[:space:]]+', ' ', 'g'))
)
order by lower(regexp_replace(btrim(t.titulo), '[[:space:]]+', ' ', 'g')), s.id
on conflict do nothing;

insert into public.catalogo_pestanas_hotel_traducciones (catalogo_pestana_id, idioma_id, titulo)
select distinct on (c.id, t.idioma_id) c.id, t.idioma_id, t.titulo
from public.hotel_detalle_secciones s
join public.hotel_detalle_secciones_traducciones es on es.seccion_id = s.id and es.idioma_id = 1
join public.hotel_detalle_secciones_traducciones t on t.seccion_id = s.id
join public.catalogo_pestanas_hotel c on lower(regexp_replace(btrim(c.titulo_es), '[[:space:]]+', ' ', 'g')) =
  lower(regexp_replace(btrim(es.titulo), '[[:space:]]+', ' ', 'g'))
order by c.id, t.idioma_id, s.id
on conflict do nothing;

