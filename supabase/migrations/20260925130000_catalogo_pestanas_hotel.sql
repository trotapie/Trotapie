-- Guardar nombre, icono y traducciones como una sola operación.
create or replace function public.guardar_catalogo_pestana_hotel(
  p_id bigint, p_titulo_es text, p_icono text, p_activo boolean, p_traducciones jsonb
)
returns bigint language plpgsql security invoker set search_path = public as $$
declare
  v_id bigint;
  traduccion jsonb;
begin
  if not (select public.puede_editar_hoteles_actual()) then raise exception 'No autorizado'; end if;
  if p_titulo_es is null or length(btrim(p_titulo_es)) not between 1 and 120 then
    raise exception 'Nombre de pestaña inválido';
  end if;
  if jsonb_typeof(p_traducciones) is distinct from 'array' then
    raise exception 'Traducciones inválidas';
  end if;

  if p_id is null then
    insert into public.catalogo_pestanas_hotel (titulo_es, icono, activo)
    values (p_titulo_es, p_icono, p_activo) returning id into v_id;
  else
    update public.catalogo_pestanas_hotel
    set titulo_es = p_titulo_es, icono = p_icono, activo = p_activo
    where id = p_id returning id into v_id;
    if v_id is null then raise exception 'Pestaña no encontrada'; end if;
  end if;

  for traduccion in select value from jsonb_array_elements(p_traducciones) loop
    insert into public.catalogo_pestanas_hotel_traducciones (catalogo_pestana_id, idioma_id, titulo)
    values (v_id, (traduccion->>'idioma_id')::bigint, traduccion->>'titulo')
    on conflict (catalogo_pestana_id, idioma_id) do update set titulo = excluded.titulo;
  end loop;
  return v_id;
end;
$$;
revoke all on function public.guardar_catalogo_pestana_hotel(bigint, text, text, boolean, jsonb) from public;
grant execute on function public.guardar_catalogo_pestana_hotel(bigint, text, text, boolean, jsonb) to authenticated;

create or replace function public.guardar_hotel_detalle_secciones(p_hotel_id bigint, p_secciones jsonb)
returns void language plpgsql security invoker set search_path = public as $$
declare
  seccion jsonb;
  traduccion jsonb;
  v_seccion_id uuid;
  v_catalogo_id bigint;
  ids uuid[] := '{}'::uuid[];
  catalogos bigint[] := '{}'::bigint[];
begin
  if not (select public.puede_editar_hoteles_actual()) then raise exception 'No autorizado'; end if;
  if jsonb_typeof(p_secciones) is distinct from 'array' then raise exception 'Secciones invalidas'; end if;

  -- Quitar primero las pestañas descartadas para liberar su opción de catálogo.
  delete from public.hotel_detalle_secciones where hotel_id = p_hotel_id
    and not (id = any(array(select (value->>'id')::uuid from jsonb_array_elements(p_secciones))));

  for seccion in select value from jsonb_array_elements(p_secciones) loop
    v_seccion_id := (seccion->>'id')::uuid;
    v_catalogo_id := (seccion->>'catalogo_pestana_id')::bigint;
    if v_seccion_id = any(ids) or v_catalogo_id = any(catalogos) then
      raise exception 'Pestaña duplicada en el hotel';
    end if;
    if not exists (select 1 from public.catalogo_pestanas_hotel where id = v_catalogo_id) then
      raise exception 'Selecciona una pestaña del catálogo';
    end if;
    if exists (select 1 from public.hotel_detalle_secciones where id = v_seccion_id and hotel_id <> p_hotel_id) then
      raise exception 'La seccion pertenece a otro hotel';
    end if;
    ids := array_append(ids, v_seccion_id);
    catalogos := array_append(catalogos, v_catalogo_id);

    if exists (select 1 from public.hotel_detalle_secciones
      where hotel_id = p_hotel_id and catalogo_pestana_id = v_catalogo_id and id <> v_seccion_id) then
      raise exception 'Pestaña duplicada en el hotel';
    end if;
    insert into public.hotel_detalle_secciones (id, hotel_id, catalogo_pestana_id, orden, icono, visible)
    select v_seccion_id, p_hotel_id, v_catalogo_id, (seccion->>'orden')::integer, c.icono,
      (seccion->>'visible')::boolean from public.catalogo_pestanas_hotel c where c.id = v_catalogo_id
    on conflict (id) do update set catalogo_pestana_id = excluded.catalogo_pestana_id,
      orden = excluded.orden, icono = excluded.icono, visible = excluded.visible;

    for traduccion in select value from jsonb_array_elements(seccion->'traducciones') loop
      insert into public.hotel_detalle_secciones_traducciones
        (seccion_id, idioma_id, contenido_html, bloques)
      values (v_seccion_id, (traduccion->>'idioma_id')::bigint,
        traduccion->>'contenido_html', traduccion->'bloques')
      on conflict (seccion_id, idioma_id) do update set
        contenido_html = excluded.contenido_html, bloques = excluded.bloques;
    end loop;
  end loop;

  delete from public.hotel_detalle_secciones where hotel_id = p_hotel_id and not (id = any(ids));
end;
$$;

