import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dotenvPath = resolve(rootDir, '.env');
const outputPath = resolve(rootDir, 'src/environments/environment.generated.ts');

function readDotenv() {
  if (!existsSync(dotenvPath)) {
    return {};
  }

  return readFileSync(dotenvPath, 'utf8').split(/\r?\n/).reduce((values, line) => {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match || line.trimStart().startsWith('#')) {
      return values;
    }

    const [, name, rawValue] = match;
    const value = rawValue.replace(/^(["'])(.*)\1$/, '$2');
    values[name] = value;
    return values;
  }, {});
}

const dotenv = readDotenv();
const supabaseUrl = process.env.SUPABASE_URL ?? dotenv.SUPABASE_URL;
const supabaseAnonKey = process.env.SUPABASE_PUBLISHABLE_KEY ?? dotenv.SUPABASE_PUBLISHABLE_KEY;

if (!supabaseUrl || !supabaseAnonKey) {
  throw new Error(
    'Faltan SUPABASE_URL o SUPABASE_PUBLISHABLE_KEY. Configuralas en Vercel o en el archivo .env local.'
  );
}

if (!/^https:\/\/[^\s]+\.supabase\.co\/?$/i.test(supabaseUrl)) {
  throw new Error('SUPABASE_URL debe ser una URL valida de Supabase.');
}

const contents = `// Generated by scripts/generate-environment.mjs. Do not commit this file.\nexport const supabaseConfig = {\n  supabaseUrl: ${JSON.stringify(supabaseUrl)},\n  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},\n} as const;\n`;

writeFileSync(outputPath, contents, 'utf8');
