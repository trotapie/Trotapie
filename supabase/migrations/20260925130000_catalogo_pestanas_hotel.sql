-- Los nombres de pestañas viven en un catálogo único; cada hotel conserva su contenido.
create or replace function public.puede_editar_hoteles_actual()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and (
      p.role = 'admin' or exists (
        select 1 from public.roles r
        join public.role_permissions rp on rp.role_id = r.id
        join public.permissions permiso on permiso.id = rp.permission_id
        where r.key = p.role and permiso.key = 'hoteles.edit'
      )
    )
  );
$$;
grant execute on function public.puede_editar_hoteles_actual() to authenticated;

create table if not exists public.catalogo_pestanas_hotel (
  id bigint generated by default as identity primary key,
  titulo_es text not null check (length(btrim(titulo_es)) between 1 and 120),
  icono text not null default 'article' check (icono in ('article', 'schedule', 'local_offer', 'info', 'restaurant', 'star')),
  activo boolean not null default true
);

create unique index if not exists catalogo_pestanas_hotel_titulo_unico
  on public.catalogo_pestanas_hotel (lower(regexp_replace(btrim(titulo_es), '[[:space:]]+', ' ', 'g')));

create table if not exists public.catalogo_pestanas_hotel_traducciones (
  catalogo_pestana_id bigint not null references public.catalogo_pestanas_hotel(id) on delete cascade,
  idioma_id bigint not null references public.idiomas(id),
  titulo text not null check (length(btrim(titulo)) > 0),
  primary key (catalogo_pestana_id, idioma_id)
);

